import json
import os
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

from actions.reminder_store import save_reminder as _store_reminder

from config import get_base_dir as _get_base_dir
_base_dir = _get_base_dir


def _get_os() -> str:
    try:
        cfg = json.loads(
            (_base_dir() / "config" / "api_keys.json").read_text(encoding="utf-8")
        )
        return cfg.get("os_system", "windows").lower()
    except Exception:
        return "windows"


def _scripts_dir() -> Path:
    d = Path.home() / ".siva" / "reminders"
    d.mkdir(parents=True, exist_ok=True)
    return d


def _sanitise(text: str, max_len: int = 200) -> str:
    return (
        text.replace("\\", "")
            .replace('"', "")
            .replace("'", "")
            .replace("\n", " ")
            .replace("\r", "")
            .strip()
    )[:max_len]


def resolve_pythonw() -> str:
    """
    The interpreter a scheduled reminder should be launched with.

    This is the whole reason reminders no longer flash a black window on the
    screen when they fire. Task Scheduler used to start powershell.exe, and
    Windows gives every console program a console — the window exists before
    -WindowStyle Hidden is ever parsed, which is why it appeared for an
    instant and then vanished. pythonw.exe is built against the GUI subsystem
    and is never given one at all, so there is nothing to flash.

    Falls back to python.exe only if no windowless interpreter can be found,
    which brings the flash back but keeps reminders working.
    """
    exe = Path(sys.executable)
    candidates = [
        exe.with_name("pythonw.exe"),                    # same venv/install
        Path(sys.base_prefix) / "pythonw.exe",           # the base install
        Path(sys.base_prefix) / "Scripts" / "pythonw.exe",
    ]
    for c in candidates:
        if c.exists():
            return str(c)

    found = shutil.which("pythonw")
    if found:
        return found

    print("[Reminder] ⚠ No pythonw.exe found — reminders may flash a window.")
    return str(exe)


def _fire_script() -> Path:
    """The script every scheduled Windows reminder runs when it comes due."""
    return _base_dir() / "actions" / "reminder_fire.py"


def _xml_escape(text: str) -> str:
    return (text.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;"))


def _write_notify_script(task_name: str, message: str, os_name: str) -> Path:
    """
    Build the script a mac or Linux reminder runs when it fires.

    Windows no longer has one: it calls actions/reminder_fire.py directly, so
    there is nothing per-reminder to generate, write out or clean up.
    """
    msg_literal = json.dumps(message)
    script_path = _scripts_dir() / f"{task_name}.py"

    if os_name == "mac":
        notify_block = f"""
message = {msg_literal}
notified = False

try:
    from plyer import notification
    notification.notify(title="S.I.V.A Reminder", message=message, timeout=15)
    notified = True
except Exception:
    pass

if not notified:
    try:
        import subprocess
        script = 'display notification "{{}}" with title "S.I.V.A Reminder"'.format(
            message.replace('"', '')
        )
        subprocess.run(["osascript", "-e", script], check=False)
    except Exception:
        pass
"""
    else:  # linux
        notify_block = f"""
message = {msg_literal}
notified = False

try:
    from plyer import notification
    notification.notify(title="S.I.V.A Reminder", message=message, timeout=15)
    notified = True
except Exception:
    pass

if not notified:
    try:
        import subprocess
        subprocess.run(
            ["notify-send", "--urgency=normal", "--expire-time=15000",
             "S.I.V.A Reminder", message],
            check=False
        )
    except Exception:
        pass
"""

    script_body = f"""# Auto-generated by S.I.V.A reminder — do not edit
import sys, os, pathlib
{notify_block}
# Self-delete after firing
try:
    pathlib.Path(__file__).unlink(missing_ok=True)
except Exception:
    pass
"""
    script_path.write_text(script_body, encoding="utf-8")
    script_path.chmod(0o600)   # owner read/write only
    return script_path

def build_task_xml(trigger_xml: str, arguments: str, description: str,
                   execution_limit: str = "PT1H") -> str:
    """
    A Task Scheduler job that fires SivaSafe silently.

    The single ExecutionTimeLimit note worth keeping in mind: an alarm window
    stays open until somebody answers it, and Task Scheduler kills a task that
    outlives its limit. PT5M was fine for a toast that showed and exited; an
    alarm needs the hour.
    """
    return (
        '<?xml version="1.0" encoding="UTF-16"?>\n'
        '<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">\n'
        f'  <RegistrationInfo><Description>{_xml_escape(description)}</Description></RegistrationInfo>\n'
        f'  <Triggers>{trigger_xml}</Triggers>\n'
        '  <Actions><Exec>\n'
        f'    <Command>{_xml_escape(resolve_pythonw())}</Command>\n'
        f'    <Arguments>{_xml_escape(arguments)}</Arguments>\n'
        f'    <WorkingDirectory>{_xml_escape(str(_base_dir()))}</WorkingDirectory>\n'
        '  </Exec></Actions>\n'
        '  <Settings>\n'
        '    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>\n'
        '    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>\n'
        '    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>\n'
        '    <StartWhenAvailable>true</StartWhenAvailable>\n'
        '    <Hidden>false</Hidden>\n'
        f'    <ExecutionTimeLimit>{execution_limit}</ExecutionTimeLimit>\n'
        '    <Enabled>true</Enabled>\n'
        '  </Settings>\n'
        '  <Principals><Principal>\n'
        '    <LogonType>InteractiveToken</LogonType>\n'
        '    <RunLevel>LeastPrivilege</RunLevel>\n'
        '  </Principal></Principals>\n'
        '</Task>'
    )


def register_task(task_name: str, xml_content: str) -> bool:
    """Hand an XML job to schtasks, replacing any task of the same name."""
    xml_path = _scripts_dir() / f"{task_name}.xml"
    try:
        xml_path.write_text(xml_content, encoding="utf-16")
        result = subprocess.run(
            ["schtasks", "/Create", "/TN", task_name, "/XML", str(xml_path), "/F"],
            capture_output=True, text=True,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    finally:
        try:
            xml_path.unlink(missing_ok=True)
        except Exception:
            pass

    if result.returncode != 0:
        print(f"[Reminder] ❌ schtasks: {(result.stderr or result.stdout).strip()}")
        return False
    return True


def delete_task(task_name: str) -> bool:
    """Remove a scheduled task. Quiet about tasks that are already gone."""
    try:
        result = subprocess.run(
            ["schtasks", "/Delete", "/TN", task_name, "/F"],
            capture_output=True, text=True,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        return result.returncode == 0
    except Exception:
        return False


def _fire_arguments(reminder_id: str, message: str,
                    kind: str = "reminder") -> str:
    return (f'"{_fire_script()}" --kind {kind} --id "{reminder_id}" '
            f'--message "{message}"')


def _schedule_windows(target_dt: datetime, task_name: str,
                      message: str) -> str:
    trigger = (
        '<TimeTrigger>'
        f'<StartBoundary>{target_dt.strftime("%Y-%m-%dT%H:%M:%S")}</StartBoundary>'
        '<Enabled>true</Enabled>'
        '</TimeTrigger>'
    )
    xml = build_task_xml(
        trigger,
        _fire_arguments(task_name, message, "reminder"),
        "SivaSafe Reminder",
    )
    return task_name if register_task(task_name, xml) else ""


def _schedule_mac(target_dt: datetime, task_name: str,
                  script_path: Path) -> str:
    agents_dir = Path.home() / "Library" / "LaunchAgents"
    agents_dir.mkdir(parents=True, exist_ok=True)

    label     = f"com.siva.reminder.{task_name}"
    plist_path = agents_dir / f"{label}.plist"

    plist_content = f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>             <string>{label}</string>
  <key>ProgramArguments</key>
  <array>
    <string>{sys.executable}</string>
    <string>{script_path}</string>
  </array>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Year</key>   <integer>{target_dt.year}</integer>
    <key>Month</key>  <integer>{target_dt.month}</integer>
    <key>Day</key>    <integer>{target_dt.day}</integer>
    <key>Hour</key>   <integer>{target_dt.hour}</integer>
    <key>Minute</key> <integer>{target_dt.minute}</integer>
  </dict>
  <key>RunAtLoad</key>         <false/>
  <key>StandardOutPath</key>   <string>/dev/null</string>
  <key>StandardErrorPath</key> <string>/dev/null</string>
</dict>
</plist>
"""
    plist_path.write_text(plist_content, encoding="utf-8")
    plist_path.chmod(0o644)

    result = subprocess.run(
        ["launchctl", "load", str(plist_path)],
        capture_output=True, text=True,
    )

    if result.returncode != 0:
        plist_path.unlink(missing_ok=True)
        script_path.unlink(missing_ok=True)
        print(f"[Reminder] ❌ launchctl: {result.stderr.strip()}")
        return ""

    return label


def _schedule_linux(target_dt: datetime, task_name: str,
                    script_path: Path) -> str:

    if shutil.which("systemd-run"):
        on_calendar = target_dt.strftime("%Y-%m-%d %H:%M:00")
        result = subprocess.run(
            [
                "systemd-run",
                "--user",
                f"--on-calendar={on_calendar}",
                f"--unit={task_name}",
                "--",
                sys.executable, str(script_path),
            ],
            capture_output=True, text=True,
        )
        if result.returncode == 0:
            return task_name
        print(f"[Reminder] ⚠️ systemd-run failed: {result.stderr.strip()}, trying 'at'")

    if shutil.which("at"):
        at_time = target_dt.strftime("%H:%M %Y-%m-%d")
        cmd_str = f"{sys.executable} {script_path}\n"
        result  = subprocess.run(
            ["at", at_time],
            input=cmd_str, capture_output=True, text=True,
        )
        if result.returncode == 0:
            return task_name
        print(f"[Reminder] ❌ at: {result.stderr.strip()}")
        return ""

    print("[Reminder] ❌ Neither systemd-run nor at found on this Linux system.")
    return ""

def reminder(
    parameters: dict,
    response=None,
    player=None,
    session_memory=None,
) -> str:

    date_str = parameters.get("date", "").strip()
    time_str = parameters.get("time", "").strip()
    message  = parameters.get("message", "Reminder").strip()

    if not date_str or not time_str:
        return "I need both a date and a time to set a reminder."

    try:
        target_dt = datetime.strptime(f"{date_str} {time_str}", "%Y-%m-%d %H:%M")
    except ValueError:
        return "I couldn't parse that date or time. Please use YYYY-MM-DD and HH:MM."

    if target_dt <= datetime.now():
        return "That time has already passed — I can't set a reminder in the past."

    os_name    = _get_os()
    safe_msg   = _sanitise(message)
    task_name  = f"SIVAReminder_{target_dt.strftime('%Y%m%d_%H%M%S')}"
    alarm      = bool(parameters.get("alarm", False))

    # Claim the SivaSafe notification identity before anything is scheduled,
    # so the toast this reminder eventually shows arrives under our own name
    # and icon rather than whatever sent it.
    if os_name == "windows":
        try:
            from core.win_notify import ensure_registered
            ensure_registered()
        except Exception:
            pass

    script_path = None
    if os_name != "windows":
        # Windows calls actions/reminder_fire.py directly; only the other two
        # platforms still need a generated script written out per reminder.
        try:
            script_path = _write_notify_script(task_name, safe_msg, os_name)
        except Exception as e:
            return f"Could not prepare the reminder script: {e}"

    try:
        if os_name == "windows":
            job_id = _schedule_windows(target_dt, task_name, safe_msg)
        elif os_name == "mac":
            job_id = _schedule_mac(target_dt, task_name, script_path)
        else:
            job_id = _schedule_linux(target_dt, task_name, script_path)
    except Exception as e:
        if script_path:
            script_path.unlink(missing_ok=True)
        print(f"[Reminder] ❌ Scheduling exception: {e}")
        return "Something went wrong while scheduling the reminder."

    if not job_id:
        if script_path:
            script_path.unlink(missing_ok=True)
        return "I couldn't register the reminder with the system scheduler."

    # Persist to JSON store so the UI can display it
    skip_store = parameters.get("skip_store", False)
    if not skip_store:
        try:
            _store_reminder(
                message=safe_msg,
                date_str=date_str,
                time_str=time_str,
                task_name=task_name,
                reminder_id=task_name,
                alarm=alarm,
            )
        except Exception as e:
            print(f"[Reminder] ⚠ Store save failed (reminder still scheduled): {e}")

    if player:
        player.write_log(f"[Reminder] ✅ {date_str} {time_str} — {safe_msg[:40]}")

    friendly_time = target_dt.strftime("%B %d at %I:%M %p")
    return f"Reminder set for {friendly_time}."


def cancel_reminder(task_name: str) -> bool:
    """Unschedule a reminder, so a deleted one cannot still go off."""
    if _get_os() != "windows" or not task_name:
        return False
    return delete_task(task_name)


def migrate_scheduled_tasks() -> int:
    """
    Re-register every reminder that has not fired yet.

    Reminders set before this change are scheduled against powershell.exe —
    they would still flash a console window and still arrive captioned
    "Windows PowerShell". schtasks /Create /F replaces a task of the same
    name, so simply writing each one again moves it onto the silent path.

    Runs on a background thread at startup. Returns how many were converted.
    """
    if _get_os() != "windows":
        return 0

    try:
        from actions.reminder_store import load_reminders
        from core.win_notify import ensure_registered
        ensure_registered()
    except Exception:
        return 0

    now = datetime.now()
    converted = 0

    for r in load_reminders():
        task_name = r.get("task_name") or r.get("id") or ""
        if not task_name:
            continue
        try:
            target = datetime.strptime(f"{r.get('date')} {r.get('time')}",
                                       "%Y-%m-%d %H:%M")
        except Exception:
            continue
        if target <= now:
            continue        # already gone off; nothing left to convert

        message = _sanitise(r.get("message", "Reminder"))
        if _schedule_windows(target, task_name, message):
            converted += 1

    # The generated .ps1 files are dead weight now — the tasks that ran them
    # no longer exist. They deleted themselves on firing, so the only ones
    # left belong to reminders that never came due.
    try:
        for stale in _scripts_dir().glob("SIVAReminder_*.ps1"):
            stale.unlink(missing_ok=True)
    except Exception:
        pass

    if converted:
        print(f"[Reminder] Converted {converted} reminder(s) to the silent notifier.")
    return converted